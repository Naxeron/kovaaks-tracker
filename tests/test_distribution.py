def test_runtime_archive_contains_only_allowlisted_payload(source_tree):
    output = source_tree / "dist" / "runtime.zip"

    assert distribution.build_distribution(output, source_dir=source_tree) == output

    expected = {
        **REQUIRED_FILES,
        "kovaaks/runtime.py": 'MESSAGE = "runtime module"\n',
    }
    expected["docs/README.md"] = expected.pop("docs/INSTALL.md")
    expected["docs/LICENSE"] = expected.pop("LICENSE")
    with zipfile.ZipFile(output) as archive:
        payload = {
            name: archive.read(name).decode("utf-8")
            for name in archive.namelist()
            if not name.endswith("/")
        }
        assert payload == {
            f"{ARCHIVE_ROOT}/{relative}": content
            for relative, content in expected.items()
        }
        root_files = {
            path.name for name in payload
            if len((path := PurePosixPath(name)).parts) == 2
        }
        assert root_files == {"kovaaks_web.py"}
        assert archive.testzip() is None


def test_runtime_archive_is_reproducible_despite_file_metadata(source_tree, tmp_path):
    first = distribution.build_distribution(tmp_path / "first.zip", source_dir=source_tree)
    for path in source_tree.rglob("*"):
        if path.is_file():
            os.utime(path, (1_000_000_000, 1_000_000_000))
            path.chmod(0o600)

    second = distribution.build_distribution(tmp_path / "second.zip", source_dir=source_tree)

    assert first.read_bytes() == second.read_bytes()


@pytest.mark.parametrize("missing", REQUIRED_FILES)
def test_missing_required_file_rejects_incomplete_archive(source_tree, tmp_path, missing):
    (source_tree / missing).unlink()
    output = tmp_path / "runtime.zip"

    with pytest.raises((OSError, ValueError)):
        distribution.build_distribution(output, source_dir=source_tree)

    assert not output.exists()


