def test_incomplete_source_preserves_previous_archive(source_tree, tmp_path):
    output = tmp_path / "runtime.zip"
    distribution.build_distribution(output, source_dir=source_tree)
    previous = output.read_bytes()
    (source_tree / "kovaaks/web/script.js").unlink()

    with pytest.raises((OSError, ValueError)):
        distribution.build_distribution(output, source_dir=source_tree)

    assert output.read_bytes() == previous


def test_mid_build_failure_preserves_previous_archive_and_cleans_temp(
    source_tree, tmp_path, monkeypatch,
):
    output = tmp_path / "dist" / "runtime.zip"
    distribution.build_distribution(output, source_dir=source_tree)
    previous = output.read_bytes()
    attempted_writes = 0

    def fail_after_first(original):
        def write(*args, **kwargs):
            nonlocal attempted_writes
            attempted_writes += 1
            if attempted_writes > 1:
                raise OSError("simulated disk write failure")
            return original(*args, **kwargs)
        return write

    monkeypatch.setattr(zipfile.ZipFile, "write", fail_after_first(zipfile.ZipFile.write))
    monkeypatch.setattr(zipfile.ZipFile, "writestr", fail_after_first(zipfile.ZipFile.writestr))

    with pytest.raises(OSError, match="simulated disk write failure"):
        distribution.build_distribution(output, source_dir=source_tree)

    assert attempted_writes > 1
    assert output.read_bytes() == previous
    assert list(output.parent.iterdir()) == [output]


def test_extracted_runtime_starts_from_unrelated_working_directory(tmp_path):
    """Exercise the shipped launcher and resources without GUI or account access."""
    output = distribution.build_distribution(tmp_path / "runtime.zip")
    extracted = tmp_path / "extracted"
    with zipfile.ZipFile(output) as archive:
        archive.extractall(extracted)
    application = extracted / ARCHIVE_ROOT
    unrelated = tmp_path / "unrelated"
    unrelated.mkdir()
    script = textwrap.dedent("""\
        import pathlib
        import runpy
        import sys
        from types import SimpleNamespace

        application = pathlib.Path(sys.argv[1]).resolve()
        sys.path.insert(0, str(application))
        initial_directory = pathlib.Path.cwd()

        def unexpected_access(*args, **kwargs):
            raise AssertionError("Runtime smoke attempted network or credential access")

        import requests
        requests.sessions.Session.request = unexpected_access
        import kovaaks.credentials as credentials
        credentials.get_password = unexpected_access
        credentials.set_password = unexpected_access
        credentials.delete_password = unexpected_access
        import kovaaks.logging_helpers as logging_helpers
        logging_helpers.LOG_FILE = str(initial_directory / "smoke.log")

        events = []
        window = object()

        class FakeAPI:
            def set_window(self, value):
                assert value is window
                events.append("set_window")

            def shutdown(self):
                events.append("shutdown")

        def create_window(title, url, **kwargs):
            assert isinstance(kwargs["js_api"], FakeAPI)
            path = pathlib.Path(url)
            assert path.is_absolute()
            assert path == application / "kovaaks" / "web" / "index.html"
            assert path.is_file()
            assert (path.parent / "script.js").is_file()
            assert (path.parent / "style.css").is_file()
            events.append("create_window")
            return window

        sys.modules["webview"] = SimpleNamespace(
            create_window=create_window,
            start=lambda **kwargs: events.append("start"),
        )
        from kovaaks import app
        assert pathlib.Path(app.__file__).resolve() == application / "kovaaks" / "app.py"
        app.KovaaksAPI = FakeAPI
        runpy.run_path(str(application / "kovaaks_web.py"), run_name="__main__")
        assert events == ["create_window", "set_window", "start", "shutdown"]
        assert pathlib.Path.cwd() == initial_directory
        print("extracted runtime started")
    """)

    result = subprocess.run(
        [sys.executable, "-c", script, str(application)],
        cwd=unrelated, capture_output=True, text=True, timeout=15,
    )

    assert result.returncode == 0, result.stdout + result.stderr
    assert "extracted runtime started" in result.stdout
